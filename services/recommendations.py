def get_recommendations(body_type: str) -> dict:
    return RECOMMENDATIONS[body_type]


def format_result_text(detection: dict) -> str:
    body_type = detection["type"]
    recommendations = get_recommendations(body_type)
    suitable = "\n".join(f"- {item}" for item in recommendations["suitable"])
    avoid = "\n".join(f"- {item}" for item in recommendations["avoid"])

    return (
        f"Ваш примерный тип фигуры: {BODY_TYPE_TITLES[body_type]}\n\n"
        f"Почему:\n"
        f"{detection['reason']} Поэтому фигура ближе к типу "
        f"\"{BODY_TYPE_TITLES[body_type]}\".\n\n"
        f"Главная задача в одежде:\n"
        f"{recommendations['goal']}\n\n"
        f"Что будет смотреться выигрышно:\n"
        f"{suitable}\n\n"
        f"Чего лучше избегать:\n"
        f"{avoid}"
    )
